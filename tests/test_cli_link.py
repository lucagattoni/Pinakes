"""`pnk link` — the authoring command, and the only machine writer of `links[]`.

Two KBs on disk in every fixture, as `test_sync_links` builds them: the `<alias>:<path>` grammar,
the partner-id refusal and the cross-KB round trip do not exist in a single-KB fixture at all.

**The byte-level tests read `read_bytes()`, never `read_text()`.** `read_text` normalises line
endings, so a comparison built on it reports "byte-identical" about a file whose newlines changed —
the mistake L5b's own CRLF check made and had to be redone (docs/RETROSPECTIVES.md).
"""

