def test_no_line_outside_the_links_block_changes_when_a_link_is_added(pair: tuple[Kb, Kb]) -> None:
    """Deliberately **not** "byte-identical": appending to an indented `links:` block re-indents
    every line of it (the next test pins that), and this fixture uses a 0-indent sequence so the
    claim in the name is the claim being made."""
    local, _partner = pair
    path = handwrite(local, "alpha", commented(local, "alpha", local.uri("gamma")))
    before = path.read_text(encoding="utf-8")
    assert link(local, "docs/alpha.md", "docs/beta.md", "cites")[0] == EXIT_OK
    after = path.read_text(encoding="utf-8")

    assert _outside_links(after) == _outside_links(before)
    assert after != before  # the block itself did change — otherwise this proves nothing


def _outside_links(text: str) -> list[str]:
    """Every line not belonging to the `links:` block, which runs to the next top-level key."""
    kept: list[str] = []
    inside = False
    for line in text.splitlines():
        if line.startswith("links:"):
            inside = True
            continue
        if inside and line[:1] not in ("", " ", "-", "#"):
            inside = False
        if not inside:
            kept.append(line)
    return kept


