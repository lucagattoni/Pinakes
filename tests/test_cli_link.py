# --- Harness -----------------------------------------------------------------------------


def link(kb: Kb, source: str, target: str, rel: str) -> tuple[int, str]:
    """Run `pnk link` against `kb`, returning `(exit code, stdout)`."""
    buffer = io.StringIO()
    with contextlib.redirect_stdout(buffer):
        code = main(["link", source, target, "--kb", str(kb.root), "--rel", rel])
    return code, buffer.getvalue()


def handwrite(kb: Kb, name: str, body: str) -> Path:
    """Replace one sidecar with hand-written text, verbatim.

    Hand-written rather than dumped: every test below is about what survives a rewrite, and a
    fixture generated by a YAML dumper carries none of the comments, quoting or indentation that
    are the thing under test.
    """
    path = kb.sidecar(name)
    path.write_text(body, encoding="utf-8")
    return path


def commented(kb: Kb, name: str, target: str) -> str:
    """A sidecar carrying every construct this increment must not destroy: comments at the top, on
    a value, inside a sequence and on a link entry; a per-link key pinakes does not know; and the
    two YAML 1.1 traps (`NO`, `no`) that must still read back as strings."""
    return f"""\
# The keeper's own note, at the top.
id: {kb.docs[name]}
title: Alpha        # trailing, on the title
tags:
  # about the tags
- policy
- "no"
links:
- to: {target}   # why this link exists
  rel: related
  note: mine to keep
country: NO
"""


@pytest.fixture
def pair(tmp_path: Path) -> tuple[Kb, Kb]:
    """A local KB with three documents and a partner it declares as `partner`."""
    local = make_kb(tmp_path / "local", "local", ["alpha", "beta", "gamma"])
    partner = make_kb(tmp_path / "partner", "partner", ["one"])
    local.connect(partner, "partner")
    return local, partner


def links_of(kb: Kb, name: str) -> list[tuple[str, str]]:
    """The `(to, rel)` pairs a sidecar carries, as `read()` resolves them."""
    parsed = read(kb.sidecar(name), owner=kb.kb_id)
    return [(str(entry.to), entry.rel) for entry in parsed.links]


