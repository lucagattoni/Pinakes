def test_each_dst_grammar_resolves(pair: tuple[Kb, Kb]) -> None:
    """A path in this KB, a `pnk://` URI, and `<alias>:<path>` — all three, on one document."""
    local, partner = pair
    assert link(local, "docs/alpha.md", "docs/beta.md", "related")[0] == EXIT_OK
    assert link(local, "docs/alpha.md", local.uri("gamma"), "cites")[0] == EXIT_OK
    assert link(local, "docs/alpha.md", "partner:docs/one.md", "counterpart")[0] == EXIT_OK

    assert links_of(local, "alpha") == [
        (local.uri("beta"), "related"),
        (local.uri("gamma"), "cites"),
        (f"pnk://{partner.kb_id}/{partner.docs['one']}", "counterpart"),
    ]


