def test_a_partner_kb_that_cannot_be_read_is_unreachable_not_a_traceback(
    pair: tuple[Kb, Kb], monkeypatch: pytest.MonkeyPatch
) -> None:
    """A partner directory this user cannot read raised `PermissionError` out of `cli.main`.

    The third instance of one class in one increment: `expanduser()`'s `RuntimeError`, `is_file()`'s
    `EACCES` on the source path, and this. Twice the fix closed the instance in front of it and
    left the rest — a defect class is not closed until it has been searched for.
    """
    local, partner = pair
    # **The refusal is injected, not built out of filesystem permissions.** Two CI runs failed here
    # while passing on macOS: `chmod(0o000)` is not a portable way to make a directory unreadable —
    # root ignores it outright, and CI's runner produced a stat that neither succeeded nor raised
    # `EACCES`, so `is_file()` answered `False` and the KB was reported as having no manifest.
    # Skipping when the precondition cannot be built leaves the guard untested exactly where it
    # broke. Raising the errno the guard exists for tests the guard on every platform.
    real_is_file = Path.is_file

    def denied(self: Path) -> bool:
        if self.is_relative_to(partner.root):
            raise PermissionError(13, "Permission denied")
        return real_is_file(self)

    monkeypatch.setattr(Path, "is_file", denied)
    with pytest.raises(PinakesError) as caught:
        add(load(local.root), source="docs/alpha.md", target="partner:docs/one.md", rel="cites")
    monkeypatch.undo()

    assert caught.value.message.startswith("linked KB `partner` ")
    # The errno text, not just the class. Asserting only the prefix left the `strerror` extraction
    # unpinned — blanking the reason kept all 42 tests green.
    assert "Permission denied" in caught.value.message


def test_a_linked_kb_path_that_will_not_expand_is_unreachable_not_a_traceback(
    pair: tuple[Kb, Kb],
) -> None:
    """`[[links.kb]] path` may be `~/kbs/partner`, so `resolve_path` calls `expanduser()` — which
    raises `RuntimeError` on an unknown user. It sat one line *above* the try that had just been
    added for exactly this class, which is how it survived four rounds of fixing that class."""
    local, _partner = pair
    manifest = local.root / "pinakes.toml"
    text = manifest.read_text(encoding="utf-8")
    manifest.write_text(
        text.replace(f'path = "{_declared_path(text)}"', 'path = "~nosuchuser12345/kb"'),
        encoding="utf-8",
    )

    with pytest.raises(PinakesError) as caught:
        add(load(local.root), source="docs/alpha.md", target="partner:docs/one.md", rel="cites")
    assert caught.value.message.startswith("linked KB `partner` ")
    # **The path it names is the one the user wrote.** Asserting only the prefix let an earlier
    # version report the *local KB root* — a real, readable directory with nothing to do with the
    # failure — while the string they typed appeared nowhere.
    assert "~nosuchuser12345/kb" in caught.value.message
    assert str(local.root) not in caught.value.message
    # And exactly one full stop: this reason is borrowed from `RuntimeError`, which ends in one.
    assert not caught.value.message.endswith("..")


def test_an_unresolvable_linked_kb_path_is_never_resolved_through_the_working_directory(
    pair: tuple[Kb, Kb], tmp_path: Path
) -> None:
    """The `pnk link` half of review 8's finding — **a misleading refusal, not a bad write.**

    Review 7 made `resolve_path` answer the declared text when it cannot resolve. That text is
    *relative*, and `_via_alias` used it as the base it read the partner's `pinakes.toml` and
    documents from, so with a directory of that literal name in the working directory the walk
    re-anchored on the CWD and genuinely read the **decoy's** manifest.

    **It stopped there**, and review 8's own account of this was wrong — corrected in review 9,
    which reproduced it. `_document_in` compares an absolute `joined.parent.resolve()` against the
    *relative* `root`, which can never be `is_relative_to`, so the refusal fires before any sidecar
    is read: `'docs/one.md' is outside \\`partner\\`` — telling the user the path they typed
    correctly is wrong, and naming neither the KB path nor the expansion failure that is the actual
    fault. The severe outcome (a permanent ULID from the wrong KB) was asserted, not measured; the
    row-deleting `pnk sync` half of the same finding is the one that is real.

    The first assertion is therefore what discriminates. The two below it are defence in depth
    against a future change that makes the decoy reachable — they were never reached under the
    round-7 mutation, which is exactly how the overstatement survived a round.

    The decoy carries the partner's own `[kb] id`, so the id-mismatch refusal cannot be what
    catches it, and a `docs/one.md` whose ULID differs from the real partner's, so the wrong answer
    is distinguishable from the right one.
    """
    local, partner = pair
    manifest = local.root / "pinakes.toml"
    text = manifest.read_text(encoding="utf-8")
    manifest.write_text(
        text.replace(f'path = "{_declared_path(text)}"', 'path = "~nosuchuser12345/kb"'),
        encoding="utf-8",
    )

    workdir = tmp_path / "workdir"
    workdir.mkdir()
    decoy = make_kb(workdir / "~nosuchuser12345" / "kb", "decoy", ["one"], kb_id=str(partner.kb_id))
    assert decoy.docs["one"] != partner.docs["one"]

    here = os.getcwd()
    os.chdir(workdir)
    try:
        with pytest.raises(PinakesError) as caught:
            add(load(local.root), source="docs/alpha.md", target="partner:docs/one.md", rel="cites")
    finally:
        os.chdir(here)

    assert "~nosuchuser12345/kb" in caught.value.message
    assert str(decoy.docs["one"]) not in caught.value.message
    assert read(local.sidecar("alpha"), owner=local.kb_id).links == ()


def _declared_path(manifest_text: str) -> str:
    """The `[[links.kb]] path` value, read back rather than assumed — `make_kb` computes it with
    `os.path.relpath`, so hard-coding it here would break the day the fixture layout moves."""
    for line in manifest_text.splitlines():
        if line.startswith("path = "):
            return line.split('"')[1]
    raise AssertionError("the fixture manifest declares no [[links.kb]] path")


